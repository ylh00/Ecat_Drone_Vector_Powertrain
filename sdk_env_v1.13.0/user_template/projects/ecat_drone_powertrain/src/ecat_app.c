/* The function is called when an error state was acknowledged by the master */
void APPL_AckErrorInd(UINT16 stateTrans)
{
    (void)stateTrans;
    s_error_led_state = 0U;
    LOGM_W(LOG_MOD_ECAT, "AL error acknowledged by master");
}

/* INIT -> PREOP: start the mailbox handler */
UINT16 APPL_StartMailboxHandler(void)
{
    LOGM_I(LOG_MOD_ECAT, "start mailbox handler (PREOP)");
    if (s_coe_enabled == 0U) {
        LOGM_W(LOG_MOD_ECAT, "CoE is disabled by parameter, only PDO communication is available");
    }
    ecat_set_al_state((uint8_t)ECAT_AL_STATE_PREOP);
    return ALSTATUSCODE_NOERROR;
}

/* PREOP -> INIT: stop the mailbox handler */
UINT16 APPL_StopMailboxHandler(void)
{
    LOGM_I(LOG_MOD_ECAT, "stop mailbox handler (INIT)");
    ecat_set_al_state((uint8_t)ECAT_AL_STATE_INIT);
    return ALSTATUSCODE_NOERROR;
}

/* PREOP -> SAFEOP: start the input handler (TxPDO is transmitted) */
UINT16 APPL_StartInputHandler(UINT16 *pIntMask)
{
    (void)pIntMask;
    LOGM_I(LOG_MOD_ECAT, "start input handler (SAFEOP)");
    ecat_set_al_state((uint8_t)ECAT_AL_STATE_SAFEOP);
    return ALSTATUSCODE_NOERROR;
}

/* SAFEOP -> PREOP: stop the input handler */
UINT16 APPL_StopInputHandler(void)
{
    LOGM_I(LOG_MOD_ECAT, "stop input handler");
    ecat_set_al_state((uint8_t)ECAT_AL_STATE_PREOP);
    return ALSTATUSCODE_NOERROR;
}

/* SAFEOP -> OP: start the output handler (RxPDO is applied) */
UINT16 APPL_StartOutputHandler(void)
{
    LOGM_I(LOG_MOD_ECAT, "start output handler (OP) - outputs may be enabled now");
    ecat_set_al_state((uint8_t)ECAT_AL_STATE_OP);
    return ALSTATUSCODE_NOERROR;
}

/* OP -> SAFEOP: stop the output handler, drop all outputs immediately */
UINT16 APPL_StopOutputHandler(void)
{
    LOGM_W(LOG_MOD_ECAT, "stop output handler - outputs disabled");
    ecat_set_al_state((uint8_t)ECAT_AL_STATE_SAFEOP);

    /* Safe state: the control task already disables the outputs because
     * g_ecat_op_active becomes 0; also clear the run bit of the RxPDO. */
    g_ecat_rxpdo.control_word = 0U;
    return ALSTATUSCODE_NOERROR;
}

/* Calculate the process data sizes from the PDO mapping.
 *   The mapping is fixed by inc/ecat_pdo.h and by SSC/ecat_drone.xlsx; the
 *   dynamic scan of the 0x1C12/0x1C13 assignment objects (as done by the
 *   generated SSC application file) is therefore not necessary. */
UINT16 APPL_GenerateMapping(UINT16 *pInputSize, UINT16 *pOutputSize)
{
    if ((pInputSize == NULL) || (pOutputSize == NULL)) {
        return ALSTATUSCODE_INVALIDINPUTMAPPING;
    }

    *pInputSize = APP_ECAT_TXPDO_SIZE;  /* TxPDO: slave -> master, 48 bytes */
    *pOutputSize = APP_ECAT_RXPDO_SIZE; /* RxPDO: master -> slave, 22 bytes */
    return ALSTATUSCODE_NOERROR;
}

/* Copy the local TxPDO to the ESC process data memory (slave -> master). */
void APPL_InputMapping(UINT16 *pData)
{
    UINT16 size = nPdInputSize;

    if (size > (UINT16)APP_ECAT_TXPDO_SIZE) {
        size = (UINT16)APP_ECAT_TXPDO_SIZE;
    }
    /* both sides are little endian, packed structs -> plain byte copy */
    memcpy((void *)pData, (const void *)&g_ecat_txpdo, size);

    s_last_input_tick_ms = g_app_tick_ms;
}

/* Copy the ESC process data memory to the local RxPDO (master -> slave). */
void APPL_OutputMapping(UINT16 *pData)
{
    UINT16 size = nPdOutputSize;

    if (size > (UINT16)APP_ECAT_RXPDO_SIZE) {
        size = (UINT16)APP_ECAT_RXPDO_SIZE;
    }
    memcpy((void *)&g_ecat_rxpdo, (const void *)pData, size);

    s_last_output_tick_ms = g_app_tick_ms;
}

/* Called from the synchronization ISR or from the main loop if no
 * synchronization is supported.  Nothing to do here: the process data is
 * evaluated by the 1 kHz control task (src/app_task.c). */
void APPL_Application(void)
{
    g_ecat_op_active = (s_al_state == (uint8_t)ECAT_AL_STATE_OP) ? 1U : 0U;
}

