/* ==========================================================================
 * CoE manufacturer object layout
 *   Object 0x2000 + n  <->  parameter id n (see inc/param.h)
 *   Sub-index 0 only, access rights and range checks are taken from the
 *   parameter descriptor.  The object dictionary entries themselves are
 *   generated by the SSC Tool from SSC/ecat_drone.xlsx, which references
 *   ecat_coe_obj_read()/ecat_coe_obj_write() in the CoeRead/CoeWrite columns.
 * ========================================================================== */
#define ECAT_COE_PARAM_OBJECT_BASE (0x2000U)

/* ==========================================================================
 * Process image (see inc/ecat_pdo.h)
 * ========================================================================== */
volatile ecat_rxpdo_t g_ecat_rxpdo;
volatile ecat_txpdo_t g_ecat_txpdo;
volatile uint8_t g_ecat_op_active = 0U;

/* ==========================================================================
 * Module state
 * ========================================================================== */
static uint8_t s_hw_ready = 0U;             /* ESC hardware + stack initialized */
static uint8_t s_al_state = ECAT_AL_STATE_INIT;
static uint8_t s_al_state_reported = 0xFF;
static volatile uint32_t s_last_output_tick_ms = 0U;
static volatile uint32_t s_last_input_tick_ms = 0U;
static uint8_t s_watchdog_warned = 0U;
static uint8_t s_run_led_state = 0U;
static uint8_t s_error_led_state = 0U;

/* Runtime parameters cached by ecat_app_apply_params() */
static uint16_t s_node_alias = 0U;
static uint8_t  s_dc_mode = 0U;
static uint32_t s_sync0_period_us = APP_CFG_ECAT_SYNC0_PERIOD_US_DEFAULT;
static uint32_t s_sync1_period_us = APP_CFG_ECAT_SYNC0_PERIOD_US_DEFAULT;
static int32_t  s_dc_shift_ns = 0;
static uint16_t s_watchdog_ms = APP_CFG_ECAT_WATCHDOG_MS_DEFAULT;
static uint8_t  s_coe_enabled = 1U;

/* ==========================================================================
 * ESC register helpers (HPM SDK register interface, hpm_esc_regs.h)
 * ========================================================================== */
static uint8_t ecat_read_al_state_reg(void)
{
    uint16_t al_stat = HPM_ESC->AL_STAT;
    uint8_t state = (uint8_t)ESC_AL_STAT_AS_GET(al_stat);

    if ((state >= (uint8_t)ECAT_AL_STATE_INIT) && (state <= (uint8_t)ECAT_AL_STATE_OP)) {
        return state;
    }
    return (uint8_t)ECAT_AL_STATE_INIT;
}

static uint16_t ecat_read_al_status_code(void)
{
    return (uint16_t)ESC_AL_STAT_CODE_CODE_GET(HPM_ESC->AL_STAT_CODE);
}

static void ecat_write_led_overrides(void)
{
    /* No dedicated RUN/ERR LED pins on this board: mirror the LED codes into
     * the ESC override registers (visible to the master and useful for debug)
     * and let the RGB status LED show the state (src/app_task.c). */
    HPM_ESC->RUN_LED_OVRD = (uint8_t)(ESC_RUN_LED_OVRD_EN_OVRD_SET(1) |
                                      ESC_RUN_LED_OVRD_LED_CODE_SET(s_run_led_state & 0x0FU));
    HPM_ESC->ERR_LED_OVRD = (uint8_t)(ESC_ERR_LED_OVRD_EN_OVRD_SET(1) |
                                      ESC_ERR_LED_OVRD_LED_CODE_SET(s_error_led_state & 0x0FU));
}

/* Update the cached AL state and notify the application state machine. */
static void ecat_set_al_state(uint8_t new_state)
{
    if (new_state == s_al_state) {
        return;
    }

    s_al_state = new_state;
    g_app_state.ecat_al_state = new_state;
    g_ecat_op_active = (new_state == (uint8_t)ECAT_AL_STATE_OP) ? 1U : 0U;

    if (new_state == (uint8_t)ECAT_AL_STATE_OP) {
        /* process data is valid from now on: restart the watchdog window */
        s_last_output_tick_ms = g_app_tick_ms;
        s_last_input_tick_ms = g_app_tick_ms;
    }

    LOGM_I(LOG_MOD_ECAT, "AL state -> %u (AL status code 0x%04X)",
           (unsigned)new_state, (unsigned)ecat_read_al_status_code());
}

/* ==========================================================================
 * Public application API (inc/ecat_app.h)
 * ========================================================================== */

/* Initialize the ESC hardware and the slave stack, then wait for the master. */
void ecat_app_init(void)
{
    hpm_stat_t stat;

    LOGM_I(LOG_MOD_ECAT, "EtherCAT slave init (ESC + SSC stack)");

    memset((void *)&g_ecat_rxpdo, 0, sizeof(g_ecat_rxpdo));
    memset((void *)&g_ecat_txpdo, 0, sizeof(g_ecat_txpdo));
    g_ecat_op_active = 0U;

    /* ESC clock tree, MII pins, PHY reset GPIOs, NMII link pins */
    board_init_ethercat(HPM_ESC);

    /* EEPROM emulation, PHY reset/config, ESC function signals, 1 ms timer,
     * SSC hardware interface and interrupts */
    stat = ecat_hardware_init(HPM_ESC);
    if (stat != status_success) {
        LOGE("EtherCAT hardware init failed (0x%08X), slave is not operational",
             (unsigned)stat);
        s_hw_ready = 0U;
        return;
    }
    s_hw_ready = 1U;

    /* Non fatal MDIO diagnostic: print the on-chip PHY identities */
    (void)ecat_phy_mdio_probe(HPM_ESC);

    /* SSC slave stack: MainInit + EEPROM callbacks + mapping sizes */
    ecat_ssc_init();

    /* Apply the EtherCAT runtime parameters (station alias, DC, watchdog) */
    ecat_app_apply_params();

    s_last_output_tick_ms = g_app_tick_ms;
    s_last_input_tick_ms = g_app_tick_ms;
    s_al_state = ecat_read_al_state_reg();
    g_app_state.ecat_al_state = s_al_state;
    ecat_set_al_state((uint8_t)ECAT_AL_STATE_INIT);
    s_al_state = ecat_read_al_state_reg();
    g_app_state.ecat_al_state = s_al_state;

    ecat_write_led_overrides();

    LOGM_I(LOG_MOD_ECAT, "EtherCAT slave initialized, waiting for master (AL state %u)",
           (unsigned)s_al_state);
}

/* Run one iteration of the slave stack.  Must be called as fast as possible. */
void ecat_app_task(void)
{
    uint8_t hw_state;

    if (s_hw_ready == 0U) {
        return;
    }

    /* ------------------------------------------------------------------ */
    /* Slave stack main loop (MainLoop of the SSC / stub)                  */
    /* ------------------------------------------------------------------ */
    ecat_ssc_loop();

    /* ------------------------------------------------------------------ */
    /* AL state monitoring                                                 */
    /*   The callbacks (APPL_Start... / APPL_Stop...) are the primary source */
    /*   of the AL state; the ESC AL Status register is used as a cross      */
    /*   check when a real stack has configured the ESC.                     */
    /* ------------------------------------------------------------------ */
    hw_state = ecat_read_al_state_reg();
    if ((hw_state >= (uint8_t)ECAT_AL_STATE_PREOP) && (hw_state <= (uint8_t)ECAT_AL_STATE_OP)) {
        ecat_set_al_state(hw_state);
    }

    if (s_al_state != s_al_state_reported) {
        s_al_state_reported = s_al_state;
        LOGM_I(LOG_MOD_ECAT, "AL state now %u", (unsigned)s_al_state);
    }
    g_app_state.ecat_al_state = s_al_state;
    g_ecat_op_active = (s_al_state == (uint8_t)ECAT_AL_STATE_OP) ? 1U : 0U;

    /* ------------------------------------------------------------------ */
    /* Process data watchdog                                               */
    /* ------------------------------------------------------------------ */
    if (s_al_state >= (uint8_t)ECAT_AL_STATE_SAFEOP) {
        if (ecat_app_watchdog_expired() != 0U) {
            if (s_watchdog_warned == 0U) {
                s_watchdog_warned = 1U;
                g_app_state.ecat_cycle_miss++;
                LOGM_W(LOG_MOD_ECAT,
                       "process data watchdog: no outputs from master for %u ms",
                       (unsigned)s_watchdog_ms);
            }
        } else if (s_watchdog_warned != 0U) {
            s_watchdog_warned = 0U;
            LOGM_I(LOG_MOD_ECAT, "process data watchdog recovered");
        }
    } else {
        s_watchdog_warned = 0U;
    }

    /* ------------------------------------------------------------------ */
    /* LED hooks (RUN/ERR codes are also driven by the RGB LED task)       */
    /* ------------------------------------------------------------------ */
    ecat_write_led_overrides();
}

/* Current AL state (cached from ESC registers when the SSC is not available) */
uint8_t ecat_app_get_al_state(void)
{
    uint8_t hw_state = ecat_read_al_state_reg();

    if ((hw_state >= (uint8_t)ECAT_AL_STATE_PREOP) && (hw_state <= (uint8_t)ECAT_AL_STATE_OP)) {
        return hw_state;
    }
    return s_al_state;
}

/* Current link status of port0 / port1 */
void ecat_app_get_link_status(uint8_t *port0, uint8_t *port1)
{
    uint16_t dl_status = HPM_ESC->ESC_DL_STAT;

    if (port0 != NULL) {
        uint8_t link = (uint8_t)ESC_ESC_DL_STAT_LP0_GET(dl_status);
#if BOARD_ECAT_PORT0_LINK_INVERT
        link = (uint8_t)(link == 0U) ? 1U : 0U;
#endif
        *port0 = link;
    }

    if (port1 != NULL) {
#if defined(BOARD_ECAT_SUPPORT_PORT1) && BOARD_ECAT_SUPPORT_PORT1
        uint8_t link1 = (uint8_t)ESC_ESC_DL_STAT_LP1_GET(dl_status);
#if BOARD_ECAT_PORT1_LINK_INVERT
        link1 = (uint8_t)(link1 == 0U) ? 1U : 0U;
#endif
        *port1 = link1;
#else
        *port1 = 0U;
#endif
    }
}

/* True when the master has requested OP and the outputs may be driven. */
uint8_t ecat_app_outputs_enabled(void)
{
    return g_ecat_op_active;
}

/* Called by the control task when the EtherCAT process data watchdog expires */
uint8_t ecat_app_watchdog_expired(void)
{
    uint32_t elapsed;

    if ((s_al_state < (uint8_t)ECAT_AL_STATE_SAFEOP) || (s_watchdog_ms == 0U)) {
        return 0U;
    }

    /* The ESC hardware watchdog (SM watchdog of the stack) is the primary
     * source; the software timeout below is an additional safety net based on
     * the age of the last APPL_OutputMapping() call. */
    if (ESC_WDG_STAT_PDAT_ST_GET(HPM_ESC->WDG_STAT_PDAT) != 0U) {
        return 1U;
    }

    elapsed = g_app_tick_ms - s_last_output_tick_ms;
    return (elapsed > (uint32_t)s_watchdog_ms) ? 1U : 0U;
}

/* Apply runtime parameters (node alias, DC mode, sync periods) to the ESC. */
void ecat_app_apply_params(void)
{
    int32_t value;

    value = param_get(PARAM_ECAT_NODE_ALIAS);
    s_node_alias = (uint16_t)APP_CLAMP(value, 0, 65535);

    value = param_get(PARAM_ECAT_DC_MODE);
    s_dc_mode = (uint8_t)APP_CLAMP(value, 0, 3);

    value = param_get(PARAM_ECAT_SYNC0_PERIOD_US);
    s_sync0_period_us = (uint32_t)APP_CLAMP(value, 125, 10000000);

    value = param_get(PARAM_ECAT_SYNC1_PERIOD_US);
    s_sync1_period_us = (uint32_t)APP_CLAMP(value, 125, 10000000);

    value = param_get(PARAM_ECAT_DC_SHIFT_NS);
    s_dc_shift_ns = APP_CLAMP(value, -1000000, 1000000);

    value = param_get(PARAM_ECAT_WATCHDOG_MS);
    s_watchdog_ms = (uint16_t)APP_CLAMP(value, 10, 1000);

    value = param_get(PARAM_ECAT_ENABLE_COE);
    s_coe_enabled = (value != 0) ? 1U : 0U;

    if (s_hw_ready != 0U) {
        /* Configured Station Alias: the master may still overwrite it, but it
         * allows a station alias to be provisioned from the PC tool without
         * changing the EEPROM image. */
        HPM_ESC->STATION_ALS = s_node_alias;

        /* Slave side DC/SYNC defaults.  The EtherCAT master configures DC and
         * the SYNC units during the INIT -> PREOP -> SAFEOP transition and
         * overwrites these values; they are the values used if the master is
         * configured to accept the slave defaults.  See also
         * ecat_app_get_sync0_period_us() etc. */
        if (s_dc_mode != 0U) {
            HPM_ESC->SYNC0_CYC_TIME = ESC_SYNC0_CYC_TIME_CYC_SET(s_sync0_period_us * 1000U);
            HPM_ESC->SYNC1_CYC_TIME = ESC_SYNC1_CYC_TIME_CYC_SET(s_sync1_period_us * 1000U);
        }
    }

    LOGM_I(LOG_MOD_ECAT,
           "params applied: alias=%u DC mode=%u SYNC0=%uus SYNC1=%uus shift=%dns wdg=%ums CoE=%u",
           (unsigned)s_node_alias, (unsigned)s_dc_mode,
           (unsigned)s_sync0_period_us, (unsigned)s_sync1_period_us,
           (int)s_dc_shift_ns, (unsigned)s_watchdog_ms, (unsigned)s_coe_enabled);
}

