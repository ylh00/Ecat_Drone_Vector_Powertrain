"""
Compile a single source file (or a set of files) of the project with exactly the
flags CMake would use, without linking.  This is the fast iteration helper for
module development:

    python check_syntax.py --build-dir <build_dir> src/dshot_bidir.c
    python check_syntax.py --build-dir <build_dir> src/*.c

It uses the compile_commands.json generated by CMake.  Relative file names are
resolved against the project directory (the parent of the build directory or the
--project argument).
"""
import argparse
import glob
import json
import os
import shlex
import subprocess
import sys


def load_commands(build_dir):
    path = os.path.join(build_dir, "compile_commands.json")
    if not os.path.exists(path):
        print("ERROR: %s not found - run cmake configure first" % path)
        sys.exit(2)
    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        return json.load(f), path


def norm(p):
    return os.path.normcase(os.path.normpath(os.path.abspath(p)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build-dir", required=True)
    ap.add_argument("--project", default=None)
    ap.add_argument("files", nargs="+")
    args = ap.parse_args()

    build_dir = os.path.abspath(args.build_dir)
    project = args.project or os.path.dirname(build_dir)
    commands, cmd_path = load_commands(build_dir)

    index = {}
    for c in commands:
        index[norm(c["file"])] = c

    targets = []
    for pattern in args.files:
        match = glob.glob(pattern)
        if not match:
            match = [pattern]
        for f in match:
            cand = [f, os.path.join(project, f)]
            hit = None
            for c in cand:
                hit = index.get(norm(c))
                if hit:
                    break
            if not hit:
                # try basename match
                base = os.path.basename(f)
                hits = [c for k, c in index.items() if os.path.basename(k) == base]
                hit = hits[0] if hits else None
            if not hit:
                print("SKIP (not in compile_commands): %s" % f)
                continue
            targets.append(hit)

    if not targets:
        print("ERROR: no compile command found")
        sys.exit(2)

    failures = 0
    for entry in targets:
        cmd = entry.get("command")
        if cmd is None:
            cmd = entry.get("arguments") and " ".join(shlex.quote(a) for a in entry["arguments"])
        words = shlex.split(cmd, posix=False)
        out = []
        skip_next = False
        for w in words:
            if skip_next:
                skip_next = False
                continue
            if w in ("-o", "-MF", "-MT", "-MQ"):
                skip_next = True
                continue
            if w == "-c":
                continue
            out.append(w)
        out.append("-fsyntax-only")
        print("== check: %s" % entry["file"])
        print("   %s" % " ".join(shlex.quote(w) for w in out))
        r = subprocess.run(out, cwd=entry["directory"])
        if r.returncode != 0:
            failures += 1
            print("FAILED: %s" % entry["file"])

    if failures:
        print("\n%d file(s) FAILED" % failures)
        sys.exit(1)
    print("\nAll %d file(s) OK" % len(targets))


if __name__ == "__main__":
    main()
