/**
 * @brief FLASH configuration option definitions (stored at flash offset 0x400):
 *
 * option[0]:
 *    [31:16] 0xfcf9 - FLASH configuration option tag
 *    [15:4]  0 - Reserved
 *    [3:0]   option words (exclude option[0])
 * option[1]:
 *    [31:28] Flash probe type (0 - SFDP SDR / 1 - SFDP DDR / 2 - 1-4-4 Read /
 *            3 - 1-2-2 Read / 4 - HyperFLASH 1.8V / 5 - HyperFLASH 3V /
 *            6 - OctaBus DDR / 8 - Xccela DDR / 10 - EcoXiP DDR)
 *    [27:24] Command Pads after Power-on Reset (0 - SPI / 1 - DPI / 2 - QPI / 3 - OPI)
 *    [23:20] Command Pads after Configuring FLASH
 *    [19:16] Quad Enable Sequence (0 - not needed / 1 - bit6 in SR1 /
 *            2 - bit1 in SR2 / 3 - bit7 in SR2 / 4 - bit1 in SR2 via 0x31)
 *    [15:8]  Dummy cycles (0 - auto-probed)
 *    [7:4]   Misc. (0 - not used / 1 - SPI mode / 2 - internal loopback / 3 - external DQS)
 *    [3:0]   Frequency option (1 - 30MHz / 2 - 50MHz / 3 - 66MHz / 4 - 80MHz /
 *            5 - 100MHz / 6 - 120MHz / 7 - 133MHz / 8 - 166MHz)
 * option[2]:
 *    [19:16] IO voltage (0 - 3V / 1 - 1.8V)
 *    [15:12] Pin group (0 - 1st group / 1 - 2nd group)
 *    [11:8]  Connection selection (0 - CA_CS0 / 1 - CB_CS0 / 2 - CA + CB)
 *    [7:0]   Drive strength (0 - default)
 * option[3]: reserved (only needed for QSPI NOR flash without JESD216 support)
 *
 * The board uses the 1 MB on-package XPI NOR flash of HPM5E3Y (P25Q80SU), the
 * option values are defined in board.h.
 */
