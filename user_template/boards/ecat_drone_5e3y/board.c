/* ==========================================================================
 * EtherCAT (ESC0 + 2 internal MII PHYs)
 * ========================================================================== */
void board_ecat_phy_reset(ESC_Type *ptr)
{
    (void) ptr;

    /* The internal MII PHY reset of HPM5E3Y is controlled by the internal
     * PV12 (PHY0) / PW12 (PHY1) pads, which are routed as GPIOs.
     * resetn is active low: assert, keep it for >= 200ns (10ms used here),
     * then release.  At least 5ms must pass after power-up/reset before the
     * PHY can be accessed via MDIO (HPM5E00 datasheet power-up requirement),
     * therefore wait BOARD_ECAT_PHY_RESET_WAIT_TIME_MS afterwards. */
    gpio_write_pin(BOARD_ECAT_PHY0_RESET_GPIO, BOARD_ECAT_PHY0_RESET_GPIO_PORT_INDEX,
                   (uint8_t) BOARD_ECAT_PHY0_RESET_PIN_INDEX, (uint8_t) BOARD_ECAT_PHY_RESET_LEVEL);
#if BOARD_ECAT_SUPPORT_PORT1
    gpio_write_pin(BOARD_ECAT_PHY1_RESET_GPIO, BOARD_ECAT_PHY1_RESET_GPIO_PORT_INDEX,
                   (uint8_t) BOARD_ECAT_PHY1_RESET_PIN_INDEX, (uint8_t) BOARD_ECAT_PHY_RESET_LEVEL);
#endif
#if BOARD_ECAT_SUPPORT_PORT2
    gpio_write_pin(BOARD_ECAT_PHY2_RESET_GPIO, BOARD_ECAT_PHY2_RESET_GPIO_PORT_INDEX,
                   (uint8_t) BOARD_ECAT_PHY2_RESET_PIN_INDEX, (uint8_t) BOARD_ECAT_PHY_RESET_LEVEL);
#endif

    board_delay_ms(BOARD_ECAT_PHY_RESET_HOLD_TIME_MS);

    /* release reset (resetn is active low) */
    gpio_write_pin(BOARD_ECAT_PHY0_RESET_GPIO, BOARD_ECAT_PHY0_RESET_GPIO_PORT_INDEX,
                   (uint8_t) BOARD_ECAT_PHY0_RESET_PIN_INDEX, (uint8_t) (!BOARD_ECAT_PHY_RESET_LEVEL));
#if BOARD_ECAT_SUPPORT_PORT1
    gpio_write_pin(BOARD_ECAT_PHY1_RESET_GPIO, BOARD_ECAT_PHY1_RESET_GPIO_PORT_INDEX,
                   (uint8_t) BOARD_ECAT_PHY1_RESET_PIN_INDEX, (uint8_t) (!BOARD_ECAT_PHY_RESET_LEVEL));
#endif
#if BOARD_ECAT_SUPPORT_PORT2
    gpio_write_pin(BOARD_ECAT_PHY2_RESET_GPIO, BOARD_ECAT_PHY2_RESET_GPIO_PORT_INDEX,
                   (uint8_t) BOARD_ECAT_PHY2_RESET_PIN_INDEX, (uint8_t) (!BOARD_ECAT_PHY_RESET_LEVEL));
#endif

    /* >= 5ms after power-up/reset is required before the first MDIO access */
    board_delay_ms(BOARD_ECAT_PHY_RESET_WAIT_TIME_MS);
}

void board_init_ethercat(ESC_Type *ptr)
{
    (void) ptr;

    init_esc0_clock();

    /* ESC pin muxing (internal PHY MII signals, MDIO/MDC, NMII link inputs,
     * REFCK) is part of init_pins().  The ESC 100MHz core clock and the 25MHz
     * PHY reference clock are enabled by ecat_hardware_init() through
     * esc_config_eeprom_and_clock() (see
     * hpm_sdk/samples/ethercat/port/hpm_ecat_hw.c and chapter 5 of the
     * "HPM5E00 series internal MII PHY user guide"). */

    /* Configure both PHY reset GPIOs and keep the PHYs in reset until
     * board_ecat_phy_reset() is called by the EtherCAT port layer. */
    gpio_set_pin_output_with_initial(BOARD_ECAT_PHY0_RESET_GPIO, BOARD_ECAT_PHY0_RESET_GPIO_PORT_INDEX,
                                     (uint8_t) BOARD_ECAT_PHY0_RESET_PIN_INDEX, (uint8_t) BOARD_ECAT_PHY_RESET_LEVEL);
#if BOARD_ECAT_SUPPORT_PORT1
    gpio_set_pin_output_with_initial(BOARD_ECAT_PHY1_RESET_GPIO, BOARD_ECAT_PHY1_RESET_GPIO_PORT_INDEX,
                                     (uint8_t) BOARD_ECAT_PHY1_RESET_PIN_INDEX, (uint8_t) BOARD_ECAT_PHY_RESET_LEVEL);
#endif
#if BOARD_ECAT_SUPPORT_PORT2
    gpio_set_pin_output_with_initial(BOARD_ECAT_PHY2_RESET_GPIO, BOARD_ECAT_PHY2_RESET_GPIO_PORT_INDEX,
                                     (uint8_t) BOARD_ECAT_PHY2_RESET_PIN_INDEX, (uint8_t) BOARD_ECAT_PHY_RESET_LEVEL);
#endif
}
