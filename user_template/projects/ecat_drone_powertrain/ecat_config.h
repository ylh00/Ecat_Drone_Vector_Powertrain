#ifndef ECAT_CONFIG_H
#define ECAT_CONFIG_H

#include "board.h"

/* ==========================================================================
 * EtherCAT EEPROM emulation in the internal flash
 *   The HPM5E3Y has a 1 MB on-chip XPI NOR flash.  The upper half starting at
 *   0x80000 is reserved for the emulated ESC EEPROM (2 Kbyte EEPROM image with
 *   wear levelling), the lower half holds the application.
 *   The parameter system uses one sector at 0x7E000 (see inc/param.h), i.e.
 *   just below the EEPROM area.
 * ========================================================================== */
#define FLASH_ADDR_BASE          BOARD_FLASH_BASE_ADDRESS
#define FLASH_SECTOR_SIZE        (0x1000U) /* 4096 bytes */

/* Please allocate appropriate flash space for FLASH EEPROM to avoid conflicts
 * with other flash content.  The EEPROM emulation component needs
 * ECAT_EEPROM_FLASH_SECTOR_CNT sectors, 64 Kbyte is more than enough for the
 * 2 Kbyte EEPROM image (16 sectors of wear levelling). */
#define FLASH_EEPROM_ADDR        (BOARD_ECAT_FLASH_EMULATE_EEPROM_ADDR) /* 0x80000 */
#define FLASH_EEPROM_SIZE        (0x10000)

/* ecat flash emulate eeprom function */
#define ECAT_EEPROM_FLASH_OFFSET      (FLASH_EEPROM_ADDR)
#define ECAT_EEPROM_FLASH_SECTOR_SIZE (FLASH_SECTOR_SIZE)
#define ECAT_EEPROM_FLASH_SECTOR_CNT  (FLASH_EEPROM_SIZE / FLASH_SECTOR_SIZE)

/* check Product Code and Revision Number in EEPROM, if not match, update the
 * EEPROM data by the included data in eeprom.h (generated by the SSC Tool) */
#define ECAT_EEPROM_CHECK_PRODUCT_CODE_AND_REVISION      (1)

/* EEPROM size in bytes, indicates the size of the actual connected EEPROM.
 * Only used when ESC_EEPROM_EMULATION == 0 (external I2C EEPROM). */
#define ECAT_EEPROM_SIZE_BYTE         (16 * 1024)  /* 16 Kbyte = 128 Kbit */

/* ==========================================================================
 * EtherCAT 1 ms timer (used by the SSC stack and by the HAL for HW_GetTimer)
 *
 * Timer allocation on the ecat_drone_5e3y board (see board.h):
 *   GPTMR0 ch0 : board_delay_us()/board_delay_ms()
 *   GPTMR0 ch1 : 1 ms board software timer (board_timer_create)
 *   GPTMR1 ch2 : DShot ESC1 telemetry capture
 *   GPTMR1 ch3 : DShot ESC2 telemetry capture
 *   GPTMR2 ch0 : EtherCAT 1 ms tick   <-- THIS FILE
 * ========================================================================== */
#define ECAT_TIMER_GPTMR        HPM_GPTMR2
#define ECAT_TIMER_GPTMR_CH     (0U)
#define ECAT_TIMER_GPTMR_CLK    (clock_gptmr2)
#define ECAT_TIMER_GPTRM_IRQ    IRQn_GPTMR2

/* Note: ECAT_TIMER_INT (call ECAT_CheckTimer() from the 1 ms timer ISR) is a
 * slave stack setting and therefore defined by the SSC generated ecat_def.h
 * (setting "ECAT_TIMER_INT" in SSC/Config/HPM_ECAT_DRONE_Config.xml, = 1).
 * The stub build defines it in SSC/StubSrc/ecat_def.h. */

/* ==========================================================================
 * ESC reset request handling (ESC_RESET interrupt, see port/hpm_ecat_hw.c)
 *   ECAT_RESET_ESC_WITH_MCU: the ESC reset request resets the whole MCU
 *                            (safest, both options are mutually exclusive)
 *   ECAT_RESET_ESC_PERIPHERAL: only reset the ESC peripheral (not suggested)
 * ========================================================================== */
#define ECAT_RESET_ESC_PERIPHERAL  0
#define ECAT_RESET_ESC_WITH_MCU    1

/* ==========================================================================
 * SSC stub (SSC/StubSrc) - build without the licensed Beckhoff slave stack
 *
 * The stub provides the SSC API so the firmware compiles, links and runs, but
 * it does NOT implement the EtherCAT protocol (no mailbox, no process data
 * exchange).  For bench testing of the application state machine the stub can
 * emulate the AL state machine (INIT -> PREOP -> SAFEOP -> OP -> ...) and drive
 * g_ecat_op_active accordingly.  This is a SMOKE TEST helper only:
 *   0 = disabled (default, AL state stays INIT, no outputs are ever enabled)
 *   1 = enabled  (the application sees a fake master; keep the motors
 *                 disconnected or the ESCs unpowered while testing!)
 * ========================================================================== */
#ifndef ECAT_SSC_STUB_TEST_MODE
#define ECAT_SSC_STUB_TEST_MODE         (0)
#endif
#define ECAT_SSC_STUB_TEST_PERIOD_MS    (500U)

/* ==========================================================================
 * Slave stack entry points (implemented in ecat.c, called by src/ecat_app.c)
 * ========================================================================== */

/* Initialize the slave stack (MainInit), wire the EEPROM emulation callbacks,
 * calculate the process data sizes and start the stack main loop. */
void ecat_ssc_init(void);

/* Run one iteration of the slave stack main loop (MainLoop).  Must be called
 * as often as possible from the application main loop. */
void ecat_ssc_loop(void);

/* Stop the slave stack main loop (used before a controlled reset). */
void ecat_ssc_stop(void);

/* ==========================================================================
 * Application <-> slave stack glue (implemented in src/ecat_app.c)
 *
 * The DC settings and the station alias are runtime parameters of the board
 * (inc/param.h).  The generated SSC stack performs the DC/SYNC setup itself
 * from the master configuration; these getters let a product specific stack
 * patch use the parameter values as slave defaults.  They are also used by the
 * application to configure the ESC SYNC cycle time registers before the master
 * takes over.
 * ========================================================================== */
uint32_t ecat_app_get_sync0_period_us(void);
uint32_t ecat_app_get_sync1_period_us(void);
uint32_t ecat_app_get_dc_shift_ns(void);
uint8_t  ecat_app_get_dc_mode(void);
uint16_t ecat_app_get_watchdog_ms(void);

#endif /* ECAT_CONFIG_H */
